// iOS 27 requires the "scene" startup system. The scene loads Main.storyboard (our MainViewController)
// and passes opened links on to Capacitor, which AppDelegate used to do.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
    var window: UIWindow?

    func scene(_ scene: UIScene, willConnectTo session: UISceneSession, options connectionOptions: UIScene.ConnectionOptions) {
        guard scene is UIWindowScene else { return }
        for context in connectionOptions.urlContexts {
            _ = ApplicationDelegateProxy.shared.application(UIApplication.shared, open: context.url, options: [:])
        }
        if let activity = connectionOptions.userActivities.first {
            _ = ApplicationDelegateProxy.shared.application(UIApplication.shared, continue: activity, restorationHandler: { _ in })
        }
    }

    func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
        for context in URLContexts {
            _ = ApplicationDelegateProxy.shared.application(UIApplication.shared, open: context.url, options: [:])
        }
    }

    func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
        _ = ApplicationDelegateProxy.shared.application(UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
    }
}

// The app's main screen. Same as Capacitor's, plus shake to undo: a shake tells the page,
// which shows the classic "Undo Move? Cancel / Undo" box when there is something to undo (src/undo.jsx).
class MainViewController: CAPBridgeViewController {
    override var canBecomeFirstResponder: Bool { true }

    // Swipe in from the left edge to go back a page, like Safari and the home-screen web app.
    override func capacitorDidLoad() {
        super.capacitorDidLoad()
        webView?.allowsBackForwardNavigationGestures = true
        // Behind the keyboard (the app shrinks to end at it): the app's own background, in light or dark mode,
        // so the see-through keyboard looks right in both.
        let appBackground = UIColor { traits in
            traits.userInterfaceStyle == .dark
                ? UIColor(red: 0x0d / 255, green: 0x0e / 255, blue: 0x12 / 255, alpha: 1) // --bg, dark
                : UIColor(red: 0xf3 / 255, green: 0xf3 / 255, blue: 0xf7 / 255, alpha: 1) // --bg, light
        }
        view.backgroundColor = appBackground
        webView?.backgroundColor = appBackground
        webView?.scrollView.backgroundColor = appBackground
    }

    override func viewDidAppear(_ animated: Bool) {
        super.viewDidAppear(animated)
        becomeFirstResponder()
    }

    override func motionEnded(_ motion: UIEvent.EventSubtype, with event: UIEvent?) {
        if motion == .motionShake {
            bridge?.webView?.evaluateJavaScript("window.dispatchEvent(new Event('rankr:shake'))", completionHandler: nil)
        } else {
            super.motionEnded(motion, with: event)
        }
    }
}
